// Regenerates src/vendor/openai/ from OpenAI's Apps SDK UI (MIT).
//
//   node scripts/sync-openai-design.mjs [path-to-unpacked-package]
//
// Without an argument it runs `npm pack @openai/apps-sdk-ui@VERSION` in a
// temporary folder. The package is React + Tailwind, so its components are
// not used; what Clippy takes from it is the dark colour scale and the SVG
// icons, copied rather than installed so the app gains no dependency (and no
// React/Tailwind peers). Bump VERSION and rerun to update.
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = '0.2.2';
const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'src', 'vendor', 'openai');

/** Clippy icon name -> the SDK's icon file. The four window caption buttons keep their own strokes. */
const ICONS = {
  play: 'Play',
  pause: 'Pause',
  clips: 'Video',
  settings: 'Settings',
  star: 'Star',
  'star-filled': 'StarFilled',
  pencil: 'Pencil',
  trash: 'Trash',
  folder: 'Folder',
  scissors: 'Scissor',
  volume: 'SoundOnReadOutLoudSpeaker',
  'volume-low': 'SoundOnReadOutLoudSpeaker',
  'volume-mute': 'SoundOffSimpleMute',
  fullscreen: 'ExpandLarge',
  'fullscreen-exit': 'CollapseLarge',
  'chevron-left': 'ChevronLeft',
  'chevron-right': 'ChevronRight',
  'chevron-down': 'ChevronDown',
  dots: 'DotsHorizontal',
  check: 'Check',
  rearm: 'ArrowRotateCw',
  alert: 'Warning',
  camera: 'Camera',
  copy: 'Copy',
};

/** The primitives that are real, plain CSS values in the dark theme. */
const GRAYS = ['0', '25', '50', '75', '100', '150', '200', '250', '300', '350', '400', '450', '550', '600', '650', '700', '750', '800', '850', '900', '1000'];
const HUES = ['green-400', 'green-500', 'red-400', 'red-500', 'orange-400', 'yellow-400', 'blue-300', 'blue-400', 'blue-500'];

let pkg = process.argv[2];
if (!pkg) {
  const tmp = mkdtempSync(join(tmpdir(), 'oai-ui-'));
  execFileSync('npm', ['pack', `@openai/apps-sdk-ui@${VERSION}`], { cwd: tmp, shell: true, stdio: 'ignore' });
  execFileSync('tar', ['xzf', `openai-apps-sdk-ui-${VERSION}.tgz`], { cwd: tmp, stdio: 'ignore' });
  pkg = join(tmp, 'package');
}
const version = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')).version;

// ---- tokens ---------------------------------------------------------------
const primitives = readFileSync(join(pkg, 'dist', 'es', 'styles', 'variables-primitive.css'), 'utf8');
const dark = primitives.match(/:where\(\[data-theme="dark"\]\)\s*\{([^}]*)\}/)?.[1] ?? '';
const grab = (name, from) => from.match(new RegExp(`--${name}:\\s*([^;]+);`))?.[1].trim();

const lines = [];
for (const g of GRAYS) {
  const v = grab(`gray-${g}`, dark);
  if (!v) throw new Error(`gray-${g} missing from the dark theme`);
  lines.push(`  --oai-gray-${g}: ${v};`);
}
for (const h of HUES) {
  const v = grab(h, primitives);
  if (!v) throw new Error(`${h} missing`);
  lines.push(`  --oai-${h}: ${v};`);
}

mkdirSync(out, { recursive: true });
writeFileSync(
  join(out, 'tokens.css'),
  `/* Generated by scripts/sync-openai-design.mjs from @openai/apps-sdk-ui ${version} (MIT, (c) OpenAI).
   Do not edit: rerun the script. app.css maps Clippy's own tokens onto these. */
:root {
${lines.join('\n')}
}
`,
);

// ---- icons ----------------------------------------------------------------
const entries = [];
for (const [name, file] of Object.entries(ICONS)) {
  const src = readFileSync(join(pkg, 'dist', 'es', 'components', 'Icon', 'svg', `${file}.js`), 'utf8');
  const viewBox = src.match(/viewBox: "([^"]+)"/)?.[1];
  const paths = [...src.matchAll(/_jsx\("path", \{([^}]*)\}\)/g)].map((m) => ({
    d: m[1].match(/d: "([^"]+)"/)?.[1],
    evenodd: /fillRule: "evenodd"/.test(m[1]),
  }));
  if (!viewBox || paths.length === 0 || paths.some((p) => !p.d)) throw new Error(`could not read ${file}`);
  entries.push(
    `  ${/^[a-z]+$/.test(name) ? name : `'${name}'`}: { viewBox: '${viewBox}', paths: [${paths
      .map((p) => `{ d: '${p.d}'${p.evenodd ? ', evenodd: true' : ''} }`)
      .join(', ')}] },`,
  );
}
writeFileSync(
  join(out, 'icons.ts'),
  `// Generated by scripts/sync-openai-design.mjs from @openai/apps-sdk-ui ${version} (MIT, (c) OpenAI).
// Do not edit: rerun the script. These are solid shapes, filled with currentColor.
export type SolidIcon = { viewBox: string; paths: { d: string; evenodd?: true }[] };

export const OPENAI_ICONS = {
${entries.join('\n')}
} satisfies Record<string, SolidIcon>;
`,
);

copyFileSync(join(pkg, 'LICENSE'), join(out, 'LICENSE'));
console.log(`openai apps-sdk-ui ${version}: ${GRAYS.length + HUES.length} tokens, ${entries.length} icons -> ${out}`);
