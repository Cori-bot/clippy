//! Generates the sound Clippy plays when it saves a screenshot.
//!
//! Run once; its output is committed. It exists for the same reason
//! `make-chime.rs` does — the sound in the repo has a recipe rather than a
//! provenance nobody can check.
//!
//! Usage: cargo run -p clippy-core --example make-shot-sound -- crates/clippy-daemon/assets/shot.wav
//!
//! A soft shutter: two short, dull ticks (open, close) over a low wooden thump.
//! The first version was a 1760 Hz sine, a shrill beep. This one has no pitch to
//! speak of, so it cannot be mistaken for the clip chime's notes — it is told
//! apart by being a tick and not a tone, as well as by being shorter.

use std::f32::consts::TAU;

const RATE: u32 = 44_100;

/// Well under the clip chime's 0.5 s: length is the first way the two are told
/// apart in the middle of a fight.
const SECONDS: f32 = 0.17;

/// A tiny deterministic noise source (xorshift), so the committed file can be
/// regenerated byte for byte.
struct Noise(u32);

impl Noise {
    fn next(&mut self) -> f32 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 17;
        self.0 ^= self.0 << 5;
        (self.0 as f32 / u32::MAX as f32) * 2.0 - 1.0
    }
}

fn main() -> anyhow::Result<()> {
    let out = std::env::args()
        .nth(1)
        .ok_or_else(|| anyhow::anyhow!("usage: make-shot-sound <output.wav>"))?;

    let total = (RATE as f32 * SECONDS) as usize;
    let mut noise = Noise(0x9E37_79B9);
    // (start in seconds, level): the shutter opening, then closing.
    let ticks = [(0.0f32, 1.0f32), (0.062, 0.62)];

    // Band-limited by a one-pole low-pass on the noise: full-band noise is a
    // hiss, and what reads as a "tick" is the dull part below ~3 kHz.
    let alpha = 1.0 - (-TAU * 3_000.0 / RATE as f32).exp();
    let mut lowpassed = 0.0f32;
    let mut pcm_f = Vec::with_capacity(total);
    for n in 0..total {
        let t = n as f32 / RATE as f32;
        lowpassed += alpha * (noise.next() - lowpassed);
        let mut sample = 0.0;
        for &(start, level) in &ticks {
            let local = t - start;
            if local < 0.0 {
                continue;
            }
            let attack = (local / 0.0015).min(1.0);
            // The tick: dull noise that is gone in about 12 ms.
            sample += lowpassed * attack * (-local * 220.0).exp() * level * 1.6;
            // The body: a short low thump, which is what makes it feel solid.
            sample += (TAU * 190.0 * local).sin() * attack * (-local * 70.0).exp() * level * 0.55;
        }
        pcm_f.push(sample);
    }

    let fade = (0.02 * RATE as f32) as usize;
    for k in 0..fade {
        pcm_f[total - 1 - k] *= k as f32 / fade as f32;
    }
    let peak = pcm_f.iter().fold(0.0f32, |p, s| p.max(s.abs()));
    let scale = 0.4 / peak;
    let mut pcm = Vec::with_capacity(total * 2);
    for sample in &pcm_f {
        pcm.extend_from_slice(&((sample * scale * f32::from(i16::MAX)) as i16).to_le_bytes());
    }

    std::fs::write(&out, clippy_core::sound::wav_from_pcm(&pcm, 1, RATE, 16))?;
    println!("wrote {out} ({} bytes)", 44 + pcm.len());
    Ok(())
}
